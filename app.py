from rdkit import Chem
from rdkit.Chem import Descriptors

def analizar_molecula(smiles):
    # 1. Convertir el texto SMILES en molécula de RDKit
    mol = Chem.MolFromSmiles(smiles)

    if mol is None:
        return "El código SMILES no es válido, revisa la estructura."

    # 2. Calcular propiedades clave para tu proyecto
    peso_molecular = Descriptors.MolWt(mol)
    logp = Descriptors.MolLogP(mol)  # Lipofilicidad (clave para solubilidad)
    tpsa = Descriptors.TPSA(mol)    # Área superficial polar (clave para absorción farmacéutica)

    # 3. Mostrar el reporte ordenado
    print("--- 🧪 REPORTE QUIMIOINFORMÁTICO ---")
    print(f"SMILES analizado: {smiles}")
    print(f"• Peso Molecular: {peso_molecular:.2f} g/mol")
    print(f"• LogP (Lipofilicidad): {logp:.2f}")
    print(f"• TPSA (Área Polar): {tpsa:.2f} Å²")
    print("-----------------------------------")

# Probemos con otra molécula famosa: ¡La Aspirina!
aspirina_smiles = "CC(=O)OC1=CC=CC=C1C(=O)O"
analizar_molecula(aspirina_smiles)

def predecir_campo_aplicacion(peso_molecular, logp, tpsa):
    # Lógica basada en filtros químicos y propiedades moleculares
    campos = []

    # Criterio general para moléculas tipo fármaco (Drug-like / Regla de Lipinski simplificada)
    if peso_molecular < 500 and logp < 5 and tpsa < 140:
        campos.append("💊 Farmacéutica (Alto potencial de biodisponibilidad oral)")

    # Criterio para agroquímicos (suelen ser moléculas más lipófilas y ligeras)
    if logp > 2 and peso_molecular < 400:
        campos.append("🌾 Agroquímicos / Pesticidas (Buena penetración en tejidos vegetales)")

    # Criterio si es muy polar o grande
    if tpsa > 100 or peso_molecular > 400:
        campos.append("🧪 Polímeros / Materiales Avanzados o Ingredientes Especiales")

    if not campos:
        campos.append("🔬 Investigación general / Compuesto de síntesis compleja")

    return campos

